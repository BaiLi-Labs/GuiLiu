import { useSyncExternalStore } from 'react';

export type Locale = 'zh-CN' | 'en-US';
const STORAGE_KEY = 'guiliu_locale';
const listeners = new Set<() => void>();

export function detectLocale(saved: string | null, languages: readonly string[]): Locale {
  if (saved === 'zh-CN' || saved === 'en-US') return saved;
  return languages[0]?.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en-US';
}

function initialLocale(): Locale {
  let saved: string | null = null;
  try {
    saved = localStorage.getItem(STORAGE_KEY);
  } catch {
    /* storage may be unavailable */
  }
  return detectLocale(saved, navigator.languages || [navigator.language]);
}

let locale = initialLocale();
export const getLocale = () => locale;
export function setLocale(next: Locale, persist = true) {
  if (persist) {
    try {
      localStorage.setItem(STORAGE_KEY, next);
    } catch {
      /* keep session preference */
    }
  }
  locale = next;
  document.documentElement.lang = next;
  listeners.forEach((listener) => listener());
}
setLocale(locale, false);
window.addEventListener('storage', (event) => {
  if (event.key === STORAGE_KEY) setLocale(detectLocale(event.newValue, navigator.languages), false);
});

function subscribe(listener: () => void) {
  listeners.add(listener);
  return () => {
    listeners.delete(listener);
  };
}
export function useI18n() {
  const current = useSyncExternalStore(subscribe, getLocale, getLocale);
  return { locale: current, setLocale, t };
}

